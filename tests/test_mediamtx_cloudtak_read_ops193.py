"""CloudTAK's media container may watch the standalone MediaMTX without a password.

GH #256 (ops #193): CloudTAK plays an ATAK feed by having its media container pull the
feed's URL. On a box that also runs the standalone MediaMTX, that pull comes from the
container's Docker network address, and MediaMTX only let localhost read without a
password, so CloudTAK's play button got a 401.
"""

import ast
import ipaddress
import os
import pathlib
import re
import subprocess
import types

import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
APP = (REPO / 'app.py').read_text(encoding='utf-8')
TREE = ast.parse(APP)

# The local deploy template's auth section (app.py run_mediamtx_deploy), as on test12.
MTX = """# MediaMTX Configuration - Generated by TAKWERX Console
logLevel: info

authMethod: internal
authInternalUsers:
- user: any
  ips: ['127.0.0.1', '::1']
  permissions:
  - action: read
  - action: publish
  - action: api
- user: hlsviewer
  pass: 8e63bc4e0eca90a7
  ips: []
  permissions:
  - action: read
- user: any
  pass: ''
  ips: []
  permissions:
  - action: read
    path: teststream
authHTTPAddress:
authHTTPExclude:
- action: api

rtsp: yes
"""


def _load(*names, **extra):
    src = ''
    for n in TREE.body:
        if isinstance(n, ast.FunctionDef) and n.name in names:
            src += ast.get_source_segment(APP, n) + '\n\n'
        elif isinstance(n, ast.Assign) and any(getattr(t, 'id', '') in names for t in n.targets):
            src += ast.get_source_segment(APP, n) + '\n\n'
    ns = {'os': os, 're': re, 'ipaddress': ipaddress, 'subprocess': subprocess,
          '_sudo_wrap': lambda c: c}
    ns.update(extra)
    exec(compile(src, 'app.py', 'exec'), ns)
    return ns


def _patch(text, subnets):
    ns = _load('_MTX_CLOUDTAK_READ_MARK', '_mediamtx_cloudtak_read_patch')
    return ns['_mediamtx_cloudtak_read_patch'](text, subnets)


def _users(text):
    return yaml.safe_load(text)['authInternalUsers']


def test_cloudtak_network_gets_read_only_and_nothing_else_changes():
    out = _patch(MTX, ['172.22.0.0/16'])
    users = _users(out)
    assert users[0] == {'user': 'any', 'ips': ['172.22.0.0/16'],
                        'permissions': [{'action': 'read'}]}
    assert users[1:] == _users(MTX)
    rest = yaml.safe_load(out)
    rest.pop('authInternalUsers')
    base = yaml.safe_load(MTX)
    base.pop('authInternalUsers')
    assert rest == base


def test_idempotent():
    once = _patch(MTX, ['172.22.0.0/16'])
    assert _patch(once, ['172.22.0.0/16']) == once


def test_follows_a_new_subnet_without_piling_up():
    once = _patch(MTX, ['172.22.0.0/16'])
    moved = _patch(once, ['172.30.0.0/16', 'fd00:1::/64'])
    assert _users(moved)[0]['ips'] == ['172.30.0.0/16', 'fd00:1::/64']
    assert moved.count('GH #256') == 1
    assert '172.22.0.0/16' not in moved


def test_removed_when_cloudtak_is_gone():
    assert _patch(_patch(MTX, ['172.22.0.0/16']), []) == MTX
    assert _patch(MTX, []) == MTX


def test_operator_entries_never_touched():
    # an operator's own read-only network entry looks the same but has no marker line
    own = MTX.replace("authInternalUsers:\n",
                      "authInternalUsers:\n- user: any\n  ips: ['10.9.0.0/16']\n"
                      "  permissions:\n  - action: read\n")
    out = _patch(own, [])
    assert out == own
    out = _patch(own, ['172.22.0.0/16'])
    assert {'user': 'any', 'ips': ['10.9.0.0/16'], 'permissions': [{'action': 'read'}]} in _users(out)


def test_unrecognised_auth_section_left_alone():
    http = MTX.replace('authInternalUsers:\n- user', 'authInternalUsers: []\nx:\n- user')
    assert _patch(http, ['172.22.0.0/16']) == http


def _subnets(inspect_out, nets, rc=0, stderr=''):
    def run(cmd, **kw):
        if cmd[:2] == ['docker', 'inspect']:
            return types.SimpleNamespace(returncode=rc, stdout=inspect_out, stderr=stderr)
        return types.SimpleNamespace(returncode=0, stdout=nets.get(cmd[-1], ''), stderr='')
    ns = _load('_cloudtak_media_subnets', subprocess=types.SimpleNamespace(run=run))
    return ns['_cloudtak_media_subnets']()


def test_subnets_come_from_the_media_containers_own_networks():
    assert _subnets('cloudtak_default ', {'cloudtak_default': '172.22.0.0/16 '}) == ['172.22.0.0/16']


def test_shared_bridge_and_wide_or_public_ranges_refused():
    nets = {'bridge': '172.17.0.0/16', 'wide': '0.0.0.0/0 10.0.0.0/8', 'pub': '8.8.8.0/24',
            'cloudtak_default': '172.22.0.0/16'}
    assert _subnets('bridge wide pub cloudtak_default', nets) == ['172.22.0.0/16']


def test_no_container_is_empty_and_docker_down_is_unknown():
    assert _subnets('', {}, rc=1, stderr='Error: No such object: cloudtak-media-1') == []
    assert _subnets('', {}, rc=1, stderr='Cannot connect to the Docker daemon') is None

    def no_docker(cmd, **kw):
        raise FileNotFoundError('docker')
    ns = _load('_cloudtak_media_subnets',
               subprocess=types.SimpleNamespace(run=no_docker, TimeoutExpired=subprocess.TimeoutExpired))
    assert ns['_cloudtak_media_subnets']() is None


def _body(name):
    return ast.get_source_segment(APP, next(n for n in TREE.body if isinstance(n, ast.FunctionDef)
                                            and n.name == name))


def test_converge_runs_at_startup_and_after_local_deploys():
    assert '_mediamtx_converge_cloudtak_read(' in _body('_startup_migrations')
    for fn in ('run_mediamtx_deploy', 'run_cloudtak_deploy', 'run_cloudtak_redeploy',
               'run_cloudtak_update'):
        assert '_mediamtx_converge_cloudtak_read(plog)' in _body(fn), fn


def test_converge_restarts_mediamtx_only_on_change_and_never_publish():
    body = _body('_mediamtx_converge_cloudtak_read')
    assert body.index('if patched == cur') < body.index("'restart', 'mediamtx'")
    assert 'publish' not in _body('_mediamtx_cloudtak_read_patch')
