"""ops #797: a CloudTAK on a remote host may watch the console's MediaMTX without a password.

With CloudTAK on a remote host and MediaMTX on the console, the remote host's media server pulls
`rtsp://stream.<name>:8554/...` over the network. The console's mediamtx.yml let only localhost
and (for a LOCAL CloudTAK) the media container's Docker network read without a password, so
MediaMTX answered the remote host with `401 Unauthorized` and CloudTAK said "Stream cannot play:
source of path ... has timed out" (found by the fresh-install cell for a remote CloudTAK).

The read entry now follows the remote host's address too (the address it was set up with, and
the address it shows to the internet, which is what the console sees on a cloud box, as in
ops #737), is removed when the remote CloudTAK is removed, and is restored on console start
from the last address seen (no remote login at start).

The converge runs here for real against a fake mediamtx.yml; the wiring into the deploy,
Update config, Update, Remove and start paths is checked on the source.
"""

import ast
import ipaddress
import os
import pathlib
import re
import socket
import subprocess
import types

import pytest
import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
APP = (REPO / 'app.py').read_text(encoding='utf-8')
TREE = ast.parse(APP)

MTX = """# MediaMTX Configuration - Generated by TAKWERX Console
logLevel: info

authMethod: internal
authInternalUsers:
- user: any
  ips: ['127.0.0.1', '::1']
  permissions:
  - action: read
  - action: publish
  - action: api
- user: hlsviewer
  pass: 8e63bc4e0eca90a7
  ips: []
  permissions:
  - action: read

rtsp: yes
"""

REMOTE_CFG = {'target_mode': 'remote', 'deployed': True,
              'remote': {'host': '10.0.1.7', 'ssh_user': 'ubuntu', 'ssh_port': 22}}


def _load(*names, **extra):
    src = ''
    for n in TREE.body:
        if isinstance(n, ast.FunctionDef) and n.name in names:
            src += ast.get_source_segment(APP, n) + '\n\n'
        elif isinstance(n, ast.Assign) and any(getattr(t, 'id', '') in names for t in n.targets):
            src += ast.get_source_segment(APP, n) + '\n\n'
    ns = {'re': re, 'ipaddress': ipaddress, 'socket': socket, 'subprocess': subprocess}
    ns.update(extra)
    exec(compile(src, 'app.py', 'exec'), ns)
    return ns


class Box:
    """A console box: a mediamtx.yml in memory, a settings dict, a remote host, systemctl calls."""

    def __init__(self, text=MTX, egress='203.0.113.9', own=('10.0.0.5',), resolve=None,
                 local_subnets=None, mtx_installed=True):
        self.text = text
        self.settings = {}
        self.egress = egress          # what the remote host answers when asked its public address
        self.own = set(own)
        self.resolve = resolve or {}
        self.local_subnets = local_subnets
        self.mtx_installed = mtx_installed
        self.systemctl = []
        self.remote_logins = 0
        self.logs = []

    def ns(self):
        box = self

        def ssh_probe(remote_cfg, cmd='echo ok', timeout=15):
            box.remote_logins += 1
            if box.egress is None:
                return False, 'timeout'
            return True, box.egress

        def run(cmd, **kw):
            box.systemctl.append(list(cmd))
            return types.SimpleNamespace(returncode=0, stdout='active\n', stderr='')

        def getaddrinfo(host, port, family=0):
            if host not in box.resolve:
                raise OSError('no such host')
            return [(family, 1, 6, '', (box.resolve[host], 0))]

        def write_priv(path, text):
            box.text = text

        def save_settings(s):
            box.settings = dict(s)

        real_os = os
        fake_os = types.SimpleNamespace(
            path=types.SimpleNamespace(
                exists=lambda p: box.mtx_installed and p in ('/usr/local/bin/mediamtx', '/usr/local/etc/mediamtx.yml'),
                expanduser=real_os.path.expanduser))
        return _load(
            '_MTX_CLOUDTAK_READ_MARK', '_mediamtx_cloudtak_read_patch', 'CLOUDTAK_REMOTE_EGRESS_KEY',
            '_cloudtak_remote_egress_ip', '_cloudtak_remote_read_ips', '_mediamtx_converge_cloudtak_read',
            os=fake_os, _ssh_probe=ssh_probe, _sudo_wrap=lambda c: c,
            subprocess=types.SimpleNamespace(run=run, TimeoutExpired=subprocess.TimeoutExpired),
            socket=types.SimpleNamespace(getaddrinfo=getaddrinfo, AF_INET=2),
            load_settings=lambda: dict(box.settings), save_settings=save_settings,
            _list_local_ipv4s=lambda: set(box.own), _read_priv=lambda p: box.text,
            _write_priv=write_priv, _get_cloudtak_deployment_config=lambda s: dict(REMOTE_CFG),
            _cloudtak_refresh_override=lambda log: None,
            _cloudtak_media_subnets=lambda: box.local_subnets)

    def converge(self, cfg, **kw):
        ns = self.ns()
        return ns['_mediamtx_converge_cloudtak_read'](self.logs.append, cfg, **kw)

    def restarts(self):
        return [c for c in self.systemctl if c[:2] == ['systemctl', 'restart']]

    def first_user(self):
        return yaml.safe_load(self.text)['authInternalUsers'][0]


def test_remote_cloudtak_host_may_read_without_a_password():
    """The customer fix: the remote host's addresses are on a read-only entry, nothing else moves."""
    box = Box()
    assert box.converge(dict(REMOTE_CFG)) is True
    assert box.first_user() == {'user': 'any', 'ips': ['10.0.1.7', '203.0.113.9'],
                                'permissions': [{'action': 'read'}]}
    users = yaml.safe_load(box.text)['authInternalUsers']
    assert users[1:] == yaml.safe_load(MTX)['authInternalUsers']      # operator's users untouched
    assert box.restarts() == [['systemctl', 'restart', 'mediamtx']]


def test_second_run_changes_nothing_and_does_not_restart():
    box = Box()
    box.converge(dict(REMOTE_CFG))
    box.systemctl.clear()
    assert box.converge(dict(REMOTE_CFG)) is False
    assert box.restarts() == []


def test_hostname_is_resolved_and_own_and_loopback_addresses_are_left_out():
    cfg = dict(REMOTE_CFG, remote={'host': 'ct.example.org'})
    box = Box(resolve={'ct.example.org': '198.51.100.4'}, egress='10.0.0.5')   # egress = this box
    box.converge(cfg)
    assert box.first_user()['ips'] == ['198.51.100.4']
    box = Box(egress='127.0.0.1')
    box.converge(dict(REMOTE_CFG))
    assert box.first_user()['ips'] == ['10.0.1.7']


def test_removed_when_the_remote_cloudtak_is_removed():
    box = Box()
    box.converge(dict(REMOTE_CFG))
    assert box.converge(dict(REMOTE_CFG, deployed=False)) is True
    assert box.text == MTX
    assert box.restarts()[-1] == ['systemctl', 'restart', 'mediamtx']


def test_no_remote_address_known_leaves_the_file_alone():
    box = Box(egress=None)
    cfg = dict(REMOTE_CFG, remote={'host': 'gone.example.org'})
    assert box.converge(cfg) is False
    assert box.text == MTX and box.restarts() == []


def test_console_start_makes_no_remote_login_and_uses_the_last_address_seen():
    box = Box()
    box.converge(dict(REMOTE_CFG))            # deploy time: asks the host, remembers its address
    assert box.settings['cloudtak_remote_egress_ip'] == '203.0.113.9'
    # the entry goes missing (operator rewrote the file), the host is unreachable at start
    box.text = MTX
    box.egress = None
    box.remote_logins = 0
    box.converge(dict(REMOTE_CFG), probe=False)
    assert box.remote_logins == 0
    assert box.first_user()['ips'] == ['10.0.1.7', '203.0.113.9']


def test_a_remote_that_does_not_answer_keeps_the_last_address_seen():
    box = Box()
    box.converge(dict(REMOTE_CFG))
    box.egress = None
    assert box.converge(dict(REMOTE_CFG)) is False      # still both addresses, no flapping
    assert box.first_user()['ips'] == ['10.0.1.7', '203.0.113.9']


def test_local_cloudtak_still_gets_its_docker_network():
    box = Box(local_subnets=['172.22.0.0/16'])
    local = {'target_mode': 'local', 'deployed': True, 'remote': {}}
    assert box.converge(local) is True
    assert box.first_user()['ips'] == ['172.22.0.0/16']
    assert box.remote_logins == 0


def test_no_standalone_mediamtx_on_this_box_is_a_no_op():
    box = Box(mtx_installed=False)
    assert box.converge(dict(REMOTE_CFG)) is False
    assert box.remote_logins == 0


def _body(name):
    return ast.get_source_segment(APP, next(n for n in TREE.body if isinstance(n, ast.FunctionDef)
                                            and n.name == name))


@pytest.mark.parametrize('fn', ['run_cloudtak_deploy', 'run_cloudtak_redeploy', 'run_cloudtak_update'])
def test_remote_deploy_update_config_and_update_set_the_entry(fn):
    assert '_mediamtx_converge_cloudtak_read(plog, cfg)' in _body(fn)


def test_remote_deploy_sets_it_after_the_deployed_flag_is_saved():
    body = _body('run_cloudtak_deploy')
    assert body.index("cfg['deployed'] = True") < body.index('_mediamtx_converge_cloudtak_read(plog, cfg)')


def test_remove_takes_the_entry_out_after_the_deployed_flag_is_cleared():
    i = APP.index("cfg['deployed'] = False\n            settings['cloudtak_deployment']")
    j = APP.index("ops #797: take the remote host's read entry out")
    assert 0 < j - i < 400
    assert "_mediamtx_converge_cloudtak_read(cfg=settings['cloudtak_deployment'])" in APP[j:j + 400]


def test_console_start_does_not_log_in_to_the_remote_host():
    body = _body('_startup_migrations')
    assert re.search(r'_mediamtx_converge_cloudtak_read\(.{0,200}?probe=False', body, re.S)
