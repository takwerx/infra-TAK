"""TerraTAK — TAK Product Center geospatial tile server (registry module).

PLAN: infra-TAK-notes docs/PLAN-terratak-module.md (W1 upload + load, W2 lifecycle).

TerraTAK is U.S. Government software distributed on tak.gov behind an account. infra-TAK
never downloads or redistributes it: the operator uploads the `docker save` tarball they
got from tak.gov, we validate it, `docker image load` it, and run it. Without a tarball
the module is inert (same pattern as the TAK Server .deb and Federation Hub).

What the W0 spike (2026-11-04, test6 + S22) established, and this file encodes:

  * The image runs as root by default. We run it as 1000:1000 with cap_drop ALL,
    no-new-privileges and a read-only rootfs. Two things that needs:
      - /tmp must be an EXEC tmpfs: T3 unpacks a JNI .so there (noexec ->
        UnsatisfiedLinkError "failed to map segment").
      - user.home must be set explicitly (-Duser.home): uid 1000 has no passwd entry,
        so Java's user.home is "?" and the TAK engine fails to open /app/?/.tak/*.sqlite.
  * T3_MAX_MEMORY is MANDATORY. Unset, every GeoTIFF tiling run segfaults in native
    libgdal TIFFClose at the end and the pipeline is marked failed. Auto-tuned per box.
  * The vendor's example Helidon security config protects writes only — every GET
    (UI, OpenAPI, tile list, tiles) stays anonymous. We add an explicit GET rule. Only
    the deprecated `security.web-server` node is honoured; `server.features.security`
    is ignored by TerraTAK (an unauthenticated DELETE got through with it).
  * With GETs authenticated, /observe/health is 401 too and no per-path exemption beats
    the /* rule, so the image's built-in HEALTHCHECK is overridden with one that reads a
    read-only credential from a :ro-mounted file (never env/compose text — both show in
    `docker inspect`).
  * The TAK JSON / TileJSON base URL comes from the request. Helidon
    requested-uri-discovery honours `Forwarded` (not X-Forwarded-*); trusted-proxies is
    pinned to this box's compose-network gateway so nothing else can steer it.

This file imports NOTHING from app.py — every seam arrives through ctx.
"""
