def _plog(msg):
    return job_log(KEY, msg)


def _state(ctx):
    return dict(ctx['load_settings']().get(SETTINGS_KEY) or {})


def _save_state(ctx, **updates):
    s = ctx['load_settings']()
    st = dict(s.get(SETTINGS_KEY) or {})
    for k, v in updates.items():
        if v is None:
            st.pop(k, None)
        else:
            st[k] = v
    s[SETTINGS_KEY] = st
    ctx['save_settings'](s)
    return st


def _docker(ctx, *args, timeout=60):
    return subprocess.run(ctx['_sudo_wrap'](['docker'] + list(args)),
                          capture_output=True, text=True, timeout=timeout)


def _image_arch(ctx, image):
    r = _docker(ctx, 'image', 'inspect', '--format', '{{.Architecture}}', image, timeout=20)
    return (r.stdout or '').strip() if r.returncode == 0 else ''


def t3_memory_mb():
    """Deterministic per-box auto-tune: MemTotal/8, clamped to [512, 2048] MiB. Always
    written (never preserved from a previous value) — W0 showed unset = native crash."""
    total_kb = 0
    try:
        with open('/proc/meminfo') as f:
            for line in f:
                if line.startswith('MemTotal:'):
                    total_kb = int(line.split()[1])
                    break
    except Exception:
        pass
    mb = (total_kb // 1024) // 8 if total_kb else T3_MIN_MB
    return max(T3_MIN_MB, min(T3_MAX_MB, mb))


# ── W1: tarball validation (before anything is loaded) ───────────────────────

def inspect_tarball(path):
    """Read the image tar's manifest + config without extracting anything to disk.

    Returns (info, error). info = {'image': 'terratak:X', 'version': 'X', 'arch': 'amd64'}.
    Refuses anything that is not exactly one image tagged terratak:<version> — a tarball
    can carry any image under any name, and `docker load` would happily install it."""
    try:
        with open(path, 'rb') as f:
            head = f.read(512)
        if len(head) < 512 or head[257:262] != b'ustar':
            return None, 'Not a tar archive. Upload the .tar file exactly as downloaded from tak.gov.'
        with tarfile.open(path, mode='r:') as tf:
            try:
                m = tf.getmember('manifest.json')
            except KeyError:
                return None, 'This tar has no manifest.json — it is not a `docker save` image archive.'
            if not m.isfile() or m.size > _MAX_MANIFEST_BYTES:
                return None, 'manifest.json in this tar is not a regular file of sane size.'
            manifest = json.loads(tf.extractfile(m).read().decode('utf-8'))
            if not isinstance(manifest, list) or len(manifest) != 1:
                return None, f'Expected exactly one image in the archive, found {len(manifest) if isinstance(manifest, list) else "?"}.'
            entry = manifest[0] or {}
            tags = entry.get('RepoTags') or []
            if len(tags) != 1 or not isinstance(tags[0], str) or not IMAGE_RE.match(tags[0]):
                return None, f'The archive is tagged {tags!r}; only a single terratak:<version> image is accepted.'
            cfg_name = entry.get('Config') or ''
            if not isinstance(cfg_name, str) or not cfg_name or cfg_name.startswith('/') or '..' in cfg_name.split('/'):
                return None, 'The archive manifest names no usable image config.'
            layers = entry.get('Layers') or []
            if not isinstance(layers, list) or not all(isinstance(x, str) and x for x in layers):
                return None, 'The archive manifest has an unusable layer list.'
            # Strict member allowlist: exactly manifest.json + the config + the layers the
            # manifest names, each once. `docker load` also honours index.json (OCI names)
            # and a legacy `repositories` file, and a duplicate manifest.json would be read
            # by docker but not by getmember() — any of those could slip a second image in
            # under a name we never validated. tak.gov's archives contain nothing else.
            allowed = {'manifest.json', cfg_name, *layers}
            seen = set()
            for mem in tf.getmembers():
                name = mem.name[2:] if mem.name.startswith('./') else mem.name
                if name in seen:
                    return None, f'The archive contains {name!r} twice — refusing it.'
                seen.add(name)
                if name not in allowed or not mem.isfile():
                    return None, (f'The archive contains {name!r}, which its manifest does not account for — '
                                  'refusing it. Upload the .tar exactly as downloaded from tak.gov.')
            try:
                c = tf.getmember(cfg_name)
            except KeyError:
                return None, 'The image config named in manifest.json is missing from the archive.'
            if not c.isfile() or c.size > _MAX_CONFIG_BYTES:
                return None, 'The image config in this tar is not a regular file of sane size.'
            cfg = json.loads(tf.extractfile(c).read().decode('utf-8'))
        arch = (cfg.get('architecture') or '').strip()
        image = tags[0]
        return {'image': image, 'version': image.split(':', 1)[1], 'arch': arch}, None
    except (tarfile.TarError, OSError, ValueError, UnicodeDecodeError) as e:
        return None, f'Could not read the archive: {str(e)[:200]}'


def _sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(4 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def load_job(ctx, job, path, info):
    """Background: hash, `docker image load`, verify, record, delete the tar."""
    plog = _plog
    try:
        plog('━━━ Step 1/4: Verifying the archive ━━━')
        host_arch = ctx['_host_arch']()
        plog(f"  Image {info['image']} · built for {info['arch'] or '?'} · this box is {host_arch}")
        size = os.path.getsize(path)
        digest = _sha256(path)
        plog(f'  sha256 {digest}')
        known = KNOWN_RELEASES.get(digest)
        if known:
            plog(f'✓ Matches the tak.gov TerraTAK {known[0]} {known[1]} release')
        else:
            plog('  ⚠ Not a release this console has a recorded hash for (newer build?). Loading it anyway — '
                 'confirm it came from tak.gov.')

        plog('')
        plog('━━━ Step 2/4: Checking Docker + disk ━━━')
        rc, dv = ctx['_docker_probe']()
        if rc != 0:
            plog('  Docker not found — installing...')
            if not ctx['_install_docker_engine'](plog):
                raise RuntimeError('Docker install failed — see log above')
        else:
            plog(f'✓ Docker present: {dv}')
        free = shutil.disk_usage('/').free
        if free < size * 3:
            raise RuntimeError(f'Not enough free disk to load the image: {free // (1 << 20)} MiB free, '
                               f'need about {size * 3 // (1 << 20)} MiB.')
        plog(f'✓ {free // (1 << 30)} GiB free')

        plog('')
        plog('━━━ Step 3/4: Loading the image (a few minutes) ━━━')
        r = _docker(ctx, 'image', 'load', '--input', path, timeout=900)
        out = ((r.stdout or '') + (r.stderr or '')).strip()
        if r.returncode != 0:
            raise RuntimeError(f'docker image load failed: {out[-400:]}')
        loaded = re.findall(r'Loaded image(?: ID)?:\s*(\S+)', out)
        if loaded != [info['image']]:
            # Never leave an unvalidated image behind in the shared image store.
            for name in loaded:
                if name != info['image']:
                    _docker(ctx, 'image', 'rm', name, timeout=120)
            raise RuntimeError(f'docker loaded {loaded!r}, expected exactly [{info["image"]!r}] — '
                               'removed the unexpected image(s)')
        got_arch = _image_arch(ctx, info['image'])
        if got_arch != host_arch:
            _docker(ctx, 'image', 'rm', info['image'], timeout=60)
            raise RuntimeError(f'Loaded image is {got_arch or "?"}, this box is {host_arch} — removed it again.')
        plog(f"✓ Loaded {info['image']} ({got_arch})")

        plog('')
        plog('━━━ Step 4/4: Recording ━━━')
        _save_state(ctx, image=info['image'], version=info['version'], arch=got_arch,
                    tar_sha256=digest, known_release=bool(known),
                    loaded_at=datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'))
        plog('✓ Image recorded. Deploy (or redeploy, to switch versions) from the TerraTAK page.')
        job.update({'running': False, 'complete': True, 'error': False})
    finally:
        try:
            os.remove(path)
        except OSError:
            pass


# ── W2: lifecycle ────────────────────────────────────────────────────────────

def _network_gateway(ctx):
    """Create the compose network if needed and return its IPv4 gateway — the address
    Helidon will see every proxied request arrive from."""
    if _docker(ctx, 'network', 'inspect', NETWORK, timeout=15).returncode != 0:
        r = _docker(ctx, 'network', 'create', NETWORK, timeout=30)
        if r.returncode != 0:
            raise RuntimeError(f'docker network create {NETWORK} failed: {(r.stderr or "").strip()[:300]}')
    r = _docker(ctx, 'network', 'inspect', '--format', '{{range .IPAM.Config}}{{.Gateway}} {{end}}',
                NETWORK, timeout=15)
    for gw in (r.stdout or '').split():
        if re.match(r'^\d{1,3}(\.\d{1,3}){3}$', gw):
            return gw
    raise RuntimeError(f'could not determine the {NETWORK} gateway address')


def _ensure_volume(ctx, image, plog):
    """Create the data volume if absent and make it writable by the container uid.
    Recursive chown only on first create — re-chowning GBs of tiles every deploy is slow."""
    fresh = _docker(ctx, 'volume', 'inspect', VOLUME, timeout=15).returncode != 0
    if fresh:
        r = _docker(ctx, 'volume', 'create', VOLUME, timeout=30)
        if r.returncode != 0:
            raise RuntimeError(f'docker volume create failed: {(r.stderr or "").strip()[:300]}')
    argv = ['run', '--rm', '--network', 'none', '--user', '0:0', '--entrypoint', 'chown',
            '-v', f'{VOLUME}:/opt/terratak', image]
    argv += (['-R', CONTAINER_UID, '/opt/terratak'] if fresh else [CONTAINER_UID, '/opt/terratak'])
    r = _docker(ctx, *argv, timeout=600)
    if r.returncode != 0:
        raise RuntimeError(f'could not set data volume ownership: {(r.stderr or "").strip()[:300]}')
    plog(f"✓ Data volume {VOLUME} {'created' if fresh else 'present'} (owned by {CONTAINER_UID})")


def _write_private(path, content, mode):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, 'w') as f:
        f.write(content)
    os.chmod(path, mode)


def _local_status(path, user=None, pw=None, method='GET', timeout=5):
    req = urllib.request.Request(f'http://127.0.0.1:{HOST_PORT}{path}', method=method)
    if user is not None:
        req.add_header('Authorization', 'Basic ' + base64.b64encode(f'{user}:{pw}'.encode()).decode())
    try:
        # No proxy: a box with http_proxy set must not route the loopback self-check out.
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        with opener.open(req, timeout=timeout) as r:
            return r.status
    except urllib.error.HTTPError as e:
        return e.code
    except Exception:
        return 0


def verify_security(admin_pw, eud_pw):
    """The config we wrote must actually be in force. Returns a list of failures."""
    checks = [
        ('anonymous GET /tilesets is refused', _local_status('/tilesets'), (401,)),
        ('anonymous GET /openapi/ui is refused', _local_status('/openapi/ui/index.html'), (401,)),
        ('anonymous DELETE is refused', _local_status('/tilesets/x', method='DELETE'), (401,)),
        ('read-only user cannot DELETE', _local_status('/tilesets/x', 'eud', eud_pw, 'DELETE'), (403,)),
        ('read-only user can read', _local_status('/tilesets', 'eud', eud_pw), (200,)),
        ('admin can read', _local_status('/tilesets', 'admin', admin_pw), (200,)),
    ]
    return [f'{name} (got HTTP {got or "no answer"})' for name, got, want in checks if got not in want]


def detect(ctx):
    st = _state(ctx)
    running = False
    health = ''
    if st.get('enabled'):
        try:
            r = ctx['probe_run'](['docker', 'inspect', '--format',
                                  '{{.State.Running}} {{if .State.Health}}{{.State.Health.Status}}{{end}}',
                                  CONTAINER], capture_output=True, text=True, timeout=3)
            parts = (r.stdout or '').split()
            running = bool(parts) and parts[0] == 'true'
            health = parts[1] if len(parts) > 1 else ''
        except Exception:
            pass
    return {'installed': bool(st.get('enabled')), 'running': running, 'health': health,
            'image': st.get('image') or '', 'version': st.get('version') or '',
            'deployed_image': st.get('deployed_image') or ''}


def deploy(ctx, job, params):
    plog = _plog
    try:
        st = _state(ctx)
        image = st.get('image')
        plog('━━━ Step 1/6: Checking the image ━━━')
        if not image or not IMAGE_RE.match(image):
            raise RuntimeError('No TerraTAK image is loaded. Upload the tarball from tak.gov first.')
        host_arch = ctx['_host_arch']()
        got = _image_arch(ctx, image)
        if not got:
            raise RuntimeError(f'{image} is recorded but not present in Docker — upload the tarball again.')
        if got != host_arch:
            raise RuntimeError(f'{image} is the {got} build; this box is {host_arch}.')
        plog(f'✓ {image} ({got})')

        plog('')
        plog('━━━ Step 2/6: Network ━━━')
        gw = _network_gateway(ctx)
        plog(f'✓ {NETWORK} (gateway {gw})')

        plog('')
        plog('━━━ Step 3/6: Writing configuration ━━━')
        admin_pw = st.get('admin_password') or secrets.token_hex(16)
        eud_pw = st.get('eud_password') or secrets.token_hex(16)
        cfg = os.path.join(INSTALL_DIR, CONFIG_SUBDIR)
        os.makedirs(INSTALL_DIR, mode=0o700, exist_ok=True)
        os.makedirs(cfg, mode=0o700, exist_ok=True)
        os.chmod(INSTALL_DIR, 0o700)
        os.chmod(cfg, 0o700)
        # The files are 0644 so container uid 1000 can read them through the bind; the
        # 0700 parent keeps every other host user out (a file bind is not path-walked).
        _write_private(os.path.join(cfg, 'terratak.yaml'),
                       HELIDON_YAML.format(proxy_re='^' + re.escape(gw) + '$',
                                           admin_pw=admin_pw, eud_pw=eud_pw), 0o644)
        _write_private(os.path.join(cfg, 'health'), f'eud:{eud_pw}', 0o644)
        t3_mb = t3_memory_mb()
        bind_opts = 'ro,Z' if ctx['os_type']() == 'rhel' else 'ro'
        _write_private(os.path.join(INSTALL_DIR, 'docker-compose.yml'), COMPOSE_YML.format(
            image=image, container=CONTAINER, uid=CONTAINER_UID, port=HOST_PORT, volume=VOLUME,
            cfg=cfg, bind_opts=bind_opts, server_mem=TERRATAK_MAX_MEMORY, t3_mem=f'{t3_mb}M',
            network=NETWORK), 0o600)
        _save_state(ctx, admin_password=admin_pw, eud_password=eud_pw)
        plog(f'✓ Helidon security config (all reads and writes need a login; writes need admin)')
        plog(f'✓ docker-compose.yml (non-root, read-only rootfs, 127.0.0.1:{HOST_PORT}, '
             f'server heap {TERRATAK_MAX_MEMORY}, tiling heap {t3_mb}M)')

        plog('')
        plog('━━━ Step 4/6: Data volume ━━━')
        _ensure_volume(ctx, image, plog)

        plog('')
        plog('━━━ Step 5/6: Starting TerraTAK ━━━')
        r = ctx['_broker_compose'](INSTALL_DIR, 'up -d --remove-orphans', timeout=300)
        if r.returncode != 0:
            raise RuntimeError(f'docker compose up failed: {((r.stderr or "") + (r.stdout or "")).strip()[-500:]}')
        deadline = time.time() + 240
        status = ''
        while time.time() < deadline:
            rr = _docker(ctx, 'inspect', '--format',
                         '{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{end}}',
                         CONTAINER, timeout=15)
            status = (rr.stdout or '').strip()
            if status.endswith('healthy') and not status.endswith('unhealthy'):
                break
            if status.startswith(('exited', 'dead')):
                break
            time.sleep(5)
        if not (status.endswith('healthy') and not status.endswith('unhealthy')):
            tail = _docker(ctx, 'logs', '--tail', '30', CONTAINER, timeout=20)
            raise RuntimeError(f'TerraTAK did not become healthy (state: {status or "unknown"}).\n'
                               + ((tail.stdout or '') + (tail.stderr or ''))[-1500:])
        plog('✓ Container healthy')

        plog('')
        plog('━━━ Step 6/6: Verifying access control ━━━')
        fails = verify_security(admin_pw, eud_pw)
        if fails:
            ctx['_broker_compose'](INSTALL_DIR, 'stop', timeout=120)
            raise RuntimeError('Security config is not in force, so TerraTAK was stopped:\n  - '
                               + '\n  - '.join(fails))
        plog('✓ Anonymous access refused, read-only user cannot write, admin can')

        prev = st.get('deployed_image')
        updates = {'enabled': True, 'deployed_image': image,
                   'deployed_at': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}
        if prev and prev != image:
            # Keep exactly one rollback image: the one we just replaced. Prune the one before it.
            older = st.get('previous_image')
            if older and older not in (image, prev):
                _docker(ctx, 'image', 'rm', older, timeout=120)
                plog(f'  Pruned {older}')
            updates['previous_image'] = prev
            plog(f'  Kept {prev} for rollback')
        _save_state(ctx, **updates)
        plog('')
        plog(f'✓ TerraTAK {st.get("version") or ""} deployed on 127.0.0.1:{HOST_PORT} (not published yet).')
        job.update({'running': False, 'complete': True, 'error': False})
    except Exception as exc:
        plog(f'ERROR: {exc}')
        job.update({'running': False, 'complete': False, 'error': True})


def uninstall(ctx, job, params):
    """Compose down, remove images + network + generated config. The tile data volume is
    kept unless the operator ticked 'also delete tile data' (params['delete_data'])."""
    steps = []
    if os.path.exists(os.path.join(INSTALL_DIR, 'docker-compose.yml')):
        ctx['_broker_compose'](INSTALL_DIR, 'down', timeout=180)
        steps.append('Container stopped and removed')
    else:
        _docker(ctx, 'rm', '-f', CONTAINER, timeout=60)
    r = _docker(ctx, 'images', '--filter', 'reference=terratak', '--format', '{{.Repository}}:{{.Tag}}', timeout=30)
    imgs = [i for i in (r.stdout or '').split() if IMAGE_RE.match(i)]
    for img in imgs:
        _docker(ctx, 'image', 'rm', img, timeout=120)
    if imgs:
        steps.append(f'Removed image(s): {", ".join(imgs)}')
    _docker(ctx, 'network', 'rm', NETWORK, timeout=30)
    if (params or {}).get('delete_data'):
        rr = _docker(ctx, 'volume', 'rm', VOLUME, timeout=120)
        steps.append('Tile data deleted' if rr.returncode == 0
                     else f'Tile data NOT deleted: {(rr.stderr or "").strip()[:200]}')
    else:
        steps.append(f'Tile data kept (Docker volume {VOLUME})')
    shutil.rmtree(INSTALL_DIR, ignore_errors=True)
    steps.append('Generated config removed')
    s = ctx['load_settings']()
    s.pop(SETTINGS_KEY, None)
    ctx['save_settings'](s)
    return {'success': True, 'steps': steps}


def _compose_argv(*action):
    return ['docker', 'compose', '--project-directory', INSTALL_DIR] + list(action)


def register(ctx):
    from flask import request, jsonify

    def upload_view():
        if job_state(KEY)['running']:
            return jsonify({'error': 'A TerraTAK job is already running — wait for it to finish.'}), 409
        f = request.files.get('file')
        if f is None or not (f.filename or '').strip():
            return jsonify({'error': 'No file uploaded'}), 400
        if not f.filename.lower().endswith('.tar'):
            return jsonify({'error': 'Upload the TerraTAK .tar archive from tak.gov (e.g. terratak-0.8.3-amd64.tar).'}), 400
        incoming = os.path.join(INSTALL_DIR, INCOMING_SUBDIR)
        os.makedirs(INSTALL_DIR, mode=0o700, exist_ok=True)
        os.makedirs(incoming, mode=0o700, exist_ok=True)
        path = os.path.join(incoming, 'upload.tar')    # fixed name: the client filename never touches disk
        f.save(path)
        info, err = inspect_tarball(path)
        if not err:
            host_arch = ctx['_host_arch']()
            if info['arch'] != host_arch:
                err = (f"This is the {info['arch'] or 'unknown-architecture'} build of {info['image']}; this box "
                       f"is {host_arch}. Download the {host_arch} archive from tak.gov.")
        if err:
            try:
                os.remove(path)
            except OSError:
                pass
            return jsonify({'error': err}), 400
        if not job_start(KEY, 'load', load_job, (ctx, job_state(KEY), path, info)):
            os.remove(path)
            return jsonify({'error': 'A TerraTAK job is already running.'}), 409
        return jsonify({'success': True, 'image': info['image'], 'arch': info['arch']})

    def logs_view():
        try:
            r = _docker(ctx, 'logs', '--tail', '200', CONTAINER, timeout=15)
            return jsonify({'lines': ((r.stdout or '') + (r.stderr or '')).splitlines()[-200:]})
        except Exception as e:
            return jsonify({'lines': [], 'error': str(e)[:200]})

    def status_view():
        du = shutil.disk_usage('/')
        return jsonify(dict(detect(ctx), disk_used_pct=round(du.used * 100 / du.total, 1)))

    register_module({
        'key': KEY,
        'name': 'TerraTAK',
        'description': 'TAK Product Center tile server — imagery, terrain and vector tiles streamed to ATAK (image from tak.gov)',
        'icon': '\U0001F5FA',   # 🗺 as escape — surrogate trap ([[apppy-emoji-surrogate-escape-trap]])
        'route': '/terratak',
        'template': 'terratak.html',
        'priority': 17,
        'detect': detect,
        'deploy': deploy,
        'uninstall': uninstall,
        'control_map': {
            'start': _compose_argv('up', '-d'),
            'stop': _compose_argv('stop'),
            'restart': _compose_argv('restart'),
        },
        'extra_routes': [
            {'url': '/api/terratak/upload', 'methods': ['POST'], 'endpoint': 'terratak_upload', 'view': upload_view},
            {'url': '/api/terratak/logs', 'methods': ['GET'], 'endpoint': 'terratak_logs', 'view': logs_view},
            {'url': '/api/terratak/status', 'methods': ['GET'], 'endpoint': 'terratak_status', 'view': status_view},
        ],
        'ports': [],                 # 127.0.0.1:8095 only; published through Caddy (W3)
        'service_units': [],
        'settings_keys': [SETTINGS_KEY],
    })
