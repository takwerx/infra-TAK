def register(ctx):
    from flask import request, jsonify

    def _lanes_view():
        return [{k: r.get(k) for k in ('id', 'user', 'channel', 'enrolled_at')} for r in (ctx['load_settings']().get('simulator_lanes') or [])]

    def channels_view():
        settings = ctx['load_settings']()
        base, headers = _ak(ctx, settings)
        if not base:
            return jsonify({'channels': [], 'error': 'Authentik not configured'}), 503
        st, res = _ak_req(base, headers, 'core/groups/?search=tak_&page_size=200&ordering=name')
        if st != 200:
            return jsonify({'channels': [], 'error': f'Authentik HTTP {st}'}), 502
        out = []
        for g in (res or {}).get('results', []):
            n = g.get('name') or ''
            if n.startswith('tak_') and not _is_admin_group(n) and _CHANNEL_RE.fullmatch(n):
                out.append({'name': n, 'channel': n[4:], 'is_simulation': n == SIM_DEFAULT_CHANNEL})
        return jsonify({'channels': out, 'default': SIM_DEFAULT_CHANNEL})

    def scenarios_view():
        sc = _scenario_mod()
        d = os.path.join(SIM_INSTALL_DIR, 'scenarios')
        out = []
        try:
            names = sorted(os.listdir(d))
        except OSError:
            names = []
        for name in names:
            if not name.endswith('.json') or not _NAME_RE.fullmatch(name[:-5]):
                continue
            entry = {'name': name[:-5], 'upload': name.startswith(SIM_UPLOAD_PREFIX)}
            try:
                with open(os.path.join(d, name), 'rb') as f:
                    doc = sc.validate_bytes(f.read(), name[:-5])
                entry.update(sc.summarize(doc))
                entry['valid'] = True
            except sc.ScenarioError as e:
                entry.update({'valid': False, 'errors': e.errors[:10]})
            except OSError as e:
                entry.update({'valid': False, 'errors': [str(e)[:120]]})
            out.append(entry)
        return jsonify({'scenarios': out})

    def upload_view():
        sc = _scenario_mod()
        if (request.content_length or 0) > SIM_MAX_UPLOAD_BYTES + 4096:
            return jsonify({'error': 'file larger than 1 MB'}), 413
        f = request.files.get('file')
        raw = f.read(SIM_MAX_UPLOAD_BYTES + 1) if f else request.get_data(cache=False)[:SIM_MAX_UPLOAD_BYTES + 1]
        if not raw:
            return jsonify({'error': 'no scenario file in the request'}), 400
        try:
            doc = sc.validate_bytes(raw, 'upload')
        except sc.ScenarioError as e:
            return jsonify({'error': 'scenario rejected', 'errors': e.errors[:20]}), 400
        name = f'{SIM_UPLOAD_PREFIX}{secrets.token_hex(4)}'
        doc['name'] = name
        d = os.path.join(SIM_INSTALL_DIR, 'scenarios')
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, f'{name}.json'), 'w') as fh:
            json.dump(doc, fh, indent=1)
        _audit(f'scenario uploaded as {name} ({doc["title"]!r}, {len(doc["entities"])} entities, {len(doc["events"])} events)')
        return jsonify({'saved': name, 'summary': sc.summarize(doc)})

    def delete_scenario_view(name):
        if not _NAME_RE.fullmatch(name or '') or not name.startswith(SIM_UPLOAD_PREFIX):
            return jsonify({'error': 'only uploaded scenarios can be deleted'}), 400
        p = os.path.join(SIM_INSTALL_DIR, 'scenarios', f'{name}.json')
        if not os.path.isfile(p):
            return jsonify({'error': 'not found'}), 404
        os.remove(p)
        _audit(f'scenario {name} deleted')
        return jsonify({'deleted': name})

    def lanes_view():
        if request.method == 'GET':
            return jsonify({'lanes': _lanes_view(), 'default': SIM_DEFAULT_CHANNEL})
        data = request.get_json(silent=True) or {}
        lane_id = str(data.get('lane') or '').strip()
        channel = str(data.get('channel') or '').strip()
        if not _LANE_ID_RE.fullmatch(lane_id) or not _CHANNEL_RE.fullmatch(channel) or _is_admin_group(channel):
            return jsonify({'error': 'lane id or channel name has an invalid format'}), 400
        try:
            rec = _ensure_lane(ctx, lane_id, channel, lambda m: print(f'[tak-simulator] {m}', flush=True))
        except ValueError as e:
            return jsonify({'error': str(e)}), 400
        except Exception as e:
            return jsonify({'error': str(e)[:300]}), 502
        return jsonify({'lane': {k: rec.get(k) for k in ('id', 'user', 'channel', 'enrolled_at')}})

    def run_view():
        data = request.get_json(silent=True) or {}
        lanes_in = data.get('lanes') or {}
        if not isinstance(lanes_in, dict) or not lanes_in:
            return jsonify({'error': 'lanes must map lane id -> channel'}), 400
        for lid, ch in lanes_in.items():
            if not _LANE_ID_RE.fullmatch(str(lid)) or not isinstance(ch, str) or not _CHANNEL_RE.fullmatch(ch) or _is_admin_group(ch):
                return jsonify({'error': f'bad lane assignment {lid!r}'}), 400
        real = sorted({ch for ch in lanes_in.values() if ch != SIM_DEFAULT_CHANNEL})
        typed = ''
        if real:
            typed = str(data.get('confirm_exercise') or '').strip()
            if typed != ', '.join(real):
                return jsonify({'error': 'a real channel needs a typed confirmation', 'confirm_required': ', '.join(real)}), 400
        plog = lambda m: print(f'[tak-simulator] {m}', flush=True)
        try:
            for lid, ch in lanes_in.items():
                _ensure_lane(ctx, str(lid), ch, plog)
        except ValueError as e:
            return jsonify({'error': str(e)}), 400
        except Exception as e:
            return jsonify({'error': str(e)[:300]}), 502
        payload = {
            'scenario': data.get('scenario'),
            'center': data.get('center'),
            'tempo': data.get('tempo', 1),
            'loop': data.get('loop'),
            'exercise': bool(real),
            'confirm_exercise': typed,      # the engine re-checks it (W9 double gate)
            'default_channel': SIM_DEFAULT_CHANNEL,
            'lanes': {str(lid): {'channel': ch, 'exercise': ch != SIM_DEFAULT_CHANNEL} for lid, ch in lanes_in.items()},
            'params': data.get('params') or {},
        }
        settings = ctx['load_settings']()
        st, res = _ctl(settings, 'POST', '/run', payload, timeout=90)
        if st == 200:
            _audit(f'run started: {res.get("scenario")} lanes={res.get("lanes")} tempo={payload["tempo"]}'
                   f'{" EXERCISE on real channel(s) " + ", ".join(real) if real else ""}')
        return jsonify(res), (200 if st == 200 else (st or 503))

    def _passthrough(path, verb):
        def view():
            settings = ctx['load_settings']()
            st, res = _ctl(settings, 'POST', path, {}, timeout=60)
            if st == 200:
                _audit(f'{verb} -> {res.get("state")}')
            return jsonify(res), (200 if st == 200 else (st or 503))
        view.__name__ = f'simulator_{verb}_view'
        return view

    def status_view():
        settings = ctx['load_settings']()
        st, res = _ctl(settings, 'GET', '/status', timeout=8)
        out = {'engine': res if st == 200 else None, 'engine_error': None if st == 200 else res.get('error'),
               'lanes': _lanes_view(), 'default': SIM_DEFAULT_CHANNEL,
               'version': get_version_info(ctx)}
        return jsonify(out)

    def logs_view():
        try:
            r = subprocess.run(ctx['_sudo_wrap'](['docker', 'logs', '--tail', '200', SIM_CONTAINER]),
                               capture_output=True, text=True, timeout=15)
            raw = (r.stdout + r.stderr).splitlines()
            return jsonify({'lines': raw[-200:]})
        except Exception as e:
            return jsonify({'lines': [], 'error': str(e)})

    def rebuild_view():
        if _rebuild_status.get('running'):
            return jsonify({'started': False, 'error': 'Rebuild already in progress'})
        _rebuild_status.update({'running': True, 'complete': False, 'error': False, 'log': []})
        threading.Thread(target=_run_rebuild, args=(ctx,), daemon=True).start()
        return jsonify({'started': True})

    def rebuild_status_view():
        return jsonify(_rebuild_status)

    register_module({
        'key': SIM_KEY,
        'name': 'TAK Simulator',
        'description': 'Scripted exercises, demos and load tests streamed into a TAK channel you pick',
        'icon': '\U0001F3AF',   # 🎯 as escape — Edit-tool surrogate trap
        'route': '/simulator',
        'template': 'simulator.html',
        'priority': 14,
        'conflicts': [],
        'detect': detect,
        'deploy': deploy,
        'uninstall': uninstall,
        'control_map': {
            'start':   lambda c: _compose_argv(c, 'up', '-d'),
            'stop':    lambda c: _compose_argv(c, 'stop'),
            'restart': lambda c: _compose_argv(c, 'restart'),
        },
        'extra_routes': [
            {'url': '/api/simulator/channels', 'methods': ['GET'], 'endpoint': 'simulator_channels', 'view': channels_view},
            {'url': '/api/simulator/scenarios', 'methods': ['GET'], 'endpoint': 'simulator_scenarios', 'view': scenarios_view},
            {'url': '/api/simulator/scenarios/upload', 'methods': ['POST'], 'endpoint': 'simulator_scenario_upload', 'view': upload_view},
            {'url': '/api/simulator/scenarios/<name>', 'methods': ['DELETE'], 'endpoint': 'simulator_scenario_delete', 'view': delete_scenario_view},
            {'url': '/api/simulator/lanes', 'methods': ['GET', 'POST'], 'endpoint': 'simulator_lanes', 'view': lanes_view},
            {'url': '/api/simulator/run', 'methods': ['POST'], 'endpoint': 'simulator_run', 'view': run_view},
            {'url': '/api/simulator/pause', 'methods': ['POST'], 'endpoint': 'simulator_pause', 'view': _passthrough('/pause', 'pause')},
            {'url': '/api/simulator/resume', 'methods': ['POST'], 'endpoint': 'simulator_resume', 'view': _passthrough('/resume', 'resume')},
            {'url': '/api/simulator/stop', 'methods': ['POST'], 'endpoint': 'simulator_stop', 'view': _passthrough('/stop', 'stop')},
            {'url': '/api/simulator/status', 'methods': ['GET'], 'endpoint': 'simulator_status', 'view': status_view},
            {'url': '/api/simulator/logs', 'methods': ['GET'], 'endpoint': 'simulator_logs', 'view': logs_view},
            {'url': '/api/simulator/rebuild', 'methods': ['POST'], 'endpoint': 'simulator_rebuild', 'view': rebuild_view},
            {'url': '/api/simulator/rebuild-status', 'methods': ['GET'], 'endpoint': 'simulator_rebuild_status', 'view': rebuild_status_view},
        ],
        'ports': [],                  # control API is 127.0.0.1:5090 only — no firewall rule (guide §9.3)
        'service_units': [],
        'settings_keys': SIM_SETTINGS_KEYS,
    })
