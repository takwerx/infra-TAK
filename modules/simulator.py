def _is_admin_group(channel):
    """tak_ROLE_ADMIN is TAK's adminGroup (CoreConfig `adminGroup="ROLE_ADMIN"`), not a
    channel: a lane enrolled there would be a TAK admin identity that reaches every
    channel. Rejected on every write path, not only hidden in the picker."""
    name = channel[4:] if channel.startswith('tak_') else channel
    return name.upper().startswith('ROLE_')

