def _stage_build_dir(plog):
    """Copy Dockerfile + engine/ from the repo into ~/tak-simulator/build (the compose
    build context) so the image always matches the console version that wrote it."""
    build = os.path.join(SIM_INSTALL_DIR, 'build')
    if os.path.isdir(build):
        shutil.rmtree(build)
    os.makedirs(build, mode=0o755)
    shutil.copy2(os.path.join(SIM_SOURCE_DIR, 'Dockerfile'), os.path.join(build, 'Dockerfile'))
    shutil.copytree(os.path.join(SIM_SOURCE_DIR, 'engine'), os.path.join(build, 'engine'),
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    plog(f'  ✓ engine source staged into {build}')


def _copy_presets(plog):
    dst = os.path.join(SIM_INSTALL_DIR, 'scenarios')
    os.makedirs(dst, mode=0o755, exist_ok=True)
    n = 0
    for name in sorted(os.listdir(os.path.join(SIM_SOURCE_DIR, 'scenarios'))):
        if name.endswith('.json') and _NAME_RE.fullmatch(name[:-5]) and not name.startswith(SIM_UPLOAD_PREFIX):
            shutil.copy2(os.path.join(SIM_SOURCE_DIR, 'scenarios', name), os.path.join(dst, name))
            os.chmod(os.path.join(dst, name), 0o644)
            n += 1
    plog(f'  ✓ {n} preset scenario(s) installed (operator uploads kept)')


def _video_base(ctx, settings):
    """rtsp://<host>:8554 when MediaMTX or TAK Video Restreamer is installed, else ''."""
    modules = ctx['detect_modules']()
    if not (modules.get('mediamtx', {}).get('installed') or modules.get('tak_video_restreamer', {}).get('installed')):
        return ''
    host = (settings.get('fqdn') or '').strip() or (settings.get('server_ip') or '').strip()
    return f'rtsp://{host}:8554' if host else ''


