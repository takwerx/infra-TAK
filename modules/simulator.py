def _ak(ctx, settings):
    """(base_url, headers) for Authentik API calls, or (None, None) when absent."""
    token = (ctx['_get_authentik_env_value'](settings, 'AUTHENTIK_BOOTSTRAP_TOKEN')
             or ctx['_get_authentik_env_value'](settings, 'AUTHENTIK_TOKEN'))
    if not token:
        return None, None
    base = ctx['_get_authentik_api_url'](settings) if ctx.get('_get_authentik_api_url') else 'http://127.0.0.1:9090'
    return base.rstrip('/') + '/api/v3', {'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'}


def _ak_req(base, headers, path, method='GET', data=None, timeout=15):
    """Authentik request -> (status, json_or_None). Never raises on HTTP errors."""
    body = json.dumps(data).encode() if data is not None else None
    req = urllib.request.Request(f'{base}/{path.lstrip("/")}', data=body, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            raw = r.read()
            return r.status, (json.loads(raw.decode()) if raw.strip() else None)
    except urllib.error.HTTPError as e:
        try:
            raw = e.read().decode()[:300]
        except Exception:
            raw = ''
        return e.code, {'_error': raw}


def _ctl(settings, method, path, data=None, timeout=15):
    """Control-API request to the container -> (status, json). 0 = unreachable."""
    token = settings.get('simulator_control_token') or ''
    body = json.dumps(data).encode() if data is not None else None
    req = urllib.request.Request(f'http://127.0.0.1:{SIM_CONTROL_PORT}{path}', data=body, method=method,
                                 headers={'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            raw = r.read()
            return r.status, (json.loads(raw.decode()) if raw.strip() else {})
    except urllib.error.HTTPError as e:
        try:
            return e.code, json.loads(e.read().decode())
        except Exception:
            return e.code, {'error': f'HTTP {e.code}'}
    except (OSError, ValueError) as e:
        return 0, {'error': f'simulator engine unreachable: {str(e)[:120]}'}


def _tak_ssl_contexts(settings):
    """Verified TLS contexts for the loopback 8446 enrollment call, tried in order — never
    CERT_NONE. (1) The public CA store with TAK's public name as SNI/hostname
    (`takserver.<fqdn>` by default, or the operator's `takserver_domain` override; 8446 serves
    the Let's Encrypt certificate wherever Caddy issued one). (2) TAK's own CA bundle
    (`/opt/tak/certs/files/{ca,root-ca,ca-trusted}.pem` — public halves, world-readable) with
    chain verification only: a box without a public name serves the TAK-signed `takserver`
    cert whose SAN is not 127.0.0.1. Returns [(label, ctx, server_hostname)]."""
    out = []
    fqdn = (settings.get('fqdn') or '').strip()
    names = []
    custom = (settings.get('takserver_domain') or '').strip()
    if custom:
        names.append(custom if '.' in custom or not fqdn else f'{custom}.{fqdn}')
    if fqdn:
        names.append(f'takserver.{fqdn}')
        names.append(fqdn)
    for n in dict.fromkeys(names):
        out.append((f'public CA / SNI {n}', ssl.create_default_context(), n))
    cas = [f for f in ('/opt/tak/certs/files/ca.pem', '/opt/tak/certs/files/root-ca.pem',
                       '/opt/tak/certs/files/ca-trusted.pem') + tuple(sorted(glob.glob('/opt/tak/certs/files/truststore-*.pem')))
           if os.path.isfile(f) and os.access(f, os.R_OK)]
    if cas:
        c = ssl.create_default_context()
        c.check_hostname = False          # TAK server certs carry SAN=takserver; chain is still CERT_REQUIRED
        loaded = 0
        for f in cas:
            try:
                c.load_verify_locations(cafile=f)
                loaded += 1
            except (ssl.SSLError, OSError):
                pass
        if loaded:
            out.append(('TAK CA bundle', c, None))
    return out


def _tak_basic(user, password, path, method='GET', body=None, headers=None, timeout=20, settings=None):
    """Loopback 8446 call with HTTP basic auth (the enrollment surface), verified against
    the public CA store (SNI = FQDN) or TAK's own CA bundle — see _tak_ssl_contexts."""
    hdrs = {'Authorization': 'Basic ' + base64.b64encode(f'{user}:{password}'.encode()).decode()}
    hdrs.update(headers or {})
    last = None
    for label, sctx, sni in _tak_ssl_contexts(settings or {}):
        try:
            conn = http.client.HTTPSConnection('127.0.0.1', 8446, context=sctx, timeout=timeout)
            if sni:
                # SNI + hostname check against the public name while dialing loopback
                sock = socket.create_connection(('127.0.0.1', 8446), timeout=timeout)
                conn.sock = sctx.wrap_socket(sock, server_hostname=sni)
            conn.request(method, path, body=body, headers=hdrs)
            r = conn.getresponse()
            data = r.read()
            conn.close()
            if r.status >= 400:
                raise urllib.error.HTTPError(f'https://127.0.0.1:8446{path}', r.status, r.reason, r.headers, None)
            return r.status, data
        except ssl.SSLCertVerificationError as e:
            last = f'{label}: {str(e)[:100]}'
            continue
    raise OSError(f'8446 certificate could not be verified ({last or "no CA available"})')


def _tcp_open(host, port, timeout=4):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


# ── lanes: Authentik identity + enrollment ────────────────────────────────────

def _ensure_group(base, headers, name):
    """Return the pk of Authentik group `name`, creating it when absent."""
    st, res = _ak_req(base, headers, f'core/groups/?name={urllib.parse.quote(name)}')
    for g in (res or {}).get('results', []) if st == 200 else []:
        if g.get('name') == name:
            return g['pk'], False
    st, res = _ak_req(base, headers, 'core/groups/', 'POST', {'name': name, 'is_superuser': False})
    if st == 201 and res and res.get('pk'):
        return res['pk'], True
    raise RuntimeError(f'could not create Authentik group {name}: HTTP {st} {(res or {}).get("_error", "")[:120]}')


def _ensure_user(base, headers, username):
    """Return (pk, created) for the lane service account."""
    st, res = _ak_req(base, headers, f'core/users/?username={urllib.parse.quote(username)}')
    for u in (res or {}).get('results', []) if st == 200 else []:
        if u.get('username') == username:
            if u.get('path') != 'users' or not u.get('is_active', True):
                _ak_req(base, headers, f'core/users/{u["pk"]}/', 'PATCH', {'path': 'users', 'is_active': True})
            return u['pk'], False
    st, res = _ak_req(base, headers, 'core/users/', 'POST', {
        'username': username, 'name': f'TAK Simulator {username}', 'is_active': True,
        'type': 'service_account', 'path': 'users'})
    if st == 201 and res and res.get('pk'):
        return res['pk'], True
    raise RuntimeError(f'could not create Authentik user {username}: HTTP {st} {(res or {}).get("_error", "")[:120]}')


def _set_membership(base, headers, user_pk, group_pk):
    """Rewrite (not union) the lane user's groups to exactly [group_pk] — it is our user."""
    st, res = _ak_req(base, headers, f'core/users/{user_pk}/', 'PATCH', {'groups': [group_pk]})
    if st not in (200, 204):
        raise RuntimeError(f'could not set lane membership: HTTP {st} {(res or {}).get("_error", "")[:120]}')


def _set_password(base, headers, user_pk, password):
    st, _ = _ak_req(base, headers, f'core/users/{user_pk}/set_password/', 'POST', {'password': password})
    if st not in (200, 204):
        raise RuntimeError(f'could not set lane password: HTTP {st}')


def _enroll(username, password, cert_path, ca_path, version, plog, settings=None):
    """TAK certificate enrollment over 8446 (§4.10 item 2): tls/config -> CSR with the
    server's nameEntries -> signClient/v2 -> cert+key PEM (600) and the CA bundle.
    The password lives only in this call; the cert is the credential afterwards."""
    import xml.etree.ElementTree as ET
    cert_dir = os.path.dirname(cert_path)
    os.makedirs(cert_dir, mode=0o700, exist_ok=True)
    last = None
    for attempt in range(1, 7):
        try:
            st, raw = _tak_basic(username, password, '/Marti/api/tls/config', settings=settings)
            break
        except urllib.error.HTTPError as e:
            last = f'HTTP {e.code}'
        except OSError as e:
            last = str(e)[:120]
        plog(f'  enrollment: tls/config not ready for {username} ({last}); retry {attempt}/6 in 5s (LDAP outpost lag)')
        time.sleep(5)
    else:
        raise RuntimeError(f'enrollment: TAK did not accept {username} on 8446 ({last})')
    entries = {}
    for el in ET.fromstring(raw).iter():
        if el.tag.endswith('nameEntry') and el.get('name') and el.get('value'):
            if not _SUBJ_VALUE_RE.fullmatch(el.get('value')) or not re.fullmatch(r'[A-Z]{1,8}', el.get('name')):
                raise RuntimeError(f'enrollment: refusing odd nameEntry {el.get("name")!r}={el.get("value")!r}')
            entries[el.get('name')] = el.get('value')
    subj = f'/CN={username}' + ''.join(f'/{k}={v}' for k, v in entries.items())
    key_path = cert_path[:-4] + '.key'
    csr_path = cert_path[:-4] + '.csr'
    for p in (key_path, csr_path, cert_path):
        with open(p, 'w'):
            pass
        os.chmod(p, 0o600)
    r = subprocess.run(['openssl', 'req', '-new', '-newkey', 'rsa:2048', '-nodes', '-keyout', key_path,
                        '-out', csr_path, '-subj', subj], capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        raise RuntimeError(f'enrollment: openssl req failed: {(r.stderr or "")[-200:]}')
    with open(csr_path) as f:
        csr_b64 = ''.join(l.strip() for l in f if not l.startswith('-----'))
    q = urllib.parse.urlencode({'clientUid': username, 'version': version})
    st, raw = _tak_basic(username, password, f'/Marti/api/tls/signClient/v2?{q}', 'POST', csr_b64.encode(),
                         {'Content-Type': 'text/plain', 'Accept': 'application/json'}, timeout=40, settings=settings)
    res = json.loads(raw.decode())
    if not res.get('signedCert'):
        raise RuntimeError('enrollment: signClient/v2 returned no certificate')

    def _pem(b64):
        der = base64.b64decode(b64)
        return subprocess.run(['openssl', 'x509', '-inform', 'DER'], input=der, capture_output=True, timeout=10).stdout.decode()

    cert_pem = _pem(res['signedCert'])
    ca_pem = ''.join(_pem(res[k]) for k in sorted(res) if k.startswith('ca'))
    if 'BEGIN CERTIFICATE' not in cert_pem or 'BEGIN CERTIFICATE' not in ca_pem:
        raise RuntimeError('enrollment: could not decode the signed certificate or CA bundle')
    with open(key_path) as f:
        key_pem = f.read()
    with open(cert_path, 'w') as f:
        f.write(cert_pem + key_pem)
    os.chmod(cert_path, 0o600)
    with open(ca_path, 'w') as f:
        f.write(ca_pem)
    os.chmod(ca_path, 0o600)
    for p in (key_path, csr_path):
        try:
            os.remove(p)
        except OSError:
            pass
    plog(f'  ✓ enrolled {username}: subject {subj}, CA bundle {ca_pem.count("BEGIN CERTIFICATE")} cert(s)')


def _write_lanes_json(settings):
    """`~/tak-simulator/certs/lanes.json` = {lane_id: channel} for the engine (W9): it
    defaults `/live` and a lane-less `/run` to every enrolled lane on its recorded channel.
    Rewritten at deploy and on every lane change; 600 like the certs beside it."""
    d = os.path.join(SIM_INSTALL_DIR, 'certs')
    if not os.path.isdir(d):
        return
    m = {str(r['id']): r['channel'] for r in (settings.get('simulator_lanes') or [])
         if r.get('id') and r.get('channel')}
    path = os.path.join(d, 'lanes.json')
    tmp = f'{path}.tmp'
    with open(tmp, 'w') as f:
        json.dump(m, f)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def _lane_record(settings, lane_id):
    for rec in settings.get('simulator_lanes') or []:
        if str(rec.get('id')) == str(lane_id):
            return rec
    return None


def _ensure_lane(ctx, lane_id, channel, plog):
    """Ensure lane `lane_id` exists, is enrolled, and is a member of exactly `channel`
    (§4.1). Creates the service account + enrolls on first use; rewrites membership on a
    channel change. Returns the lane record. Persists settings."""
    if not _LANE_ID_RE.fullmatch(str(lane_id)):
        raise ValueError('bad lane id')
    if not _CHANNEL_RE.fullmatch(channel) or _is_admin_group(channel):
        raise ValueError('bad channel name')
    settings = ctx['load_settings']()
    base, headers = _ak(ctx, settings)
    if not base:
        raise RuntimeError('Authentik is not configured — the simulator needs Authentik LDAP')
    st, res = _ak_req(base, headers, f'core/groups/?name={urllib.parse.quote(channel)}')
    gpk = next((g['pk'] for g in (res or {}).get('results', []) if g.get('name') == channel), None) if st == 200 else None
    if not gpk:
        raise ValueError(f'channel {channel} does not exist in Authentik')
    username = f'{SIM_LANE_USER_PREFIX}{lane_id}'
    cert_dir = os.path.join(SIM_INSTALL_DIR, 'certs')
    cert_path = os.path.join(cert_dir, f'lane-{lane_id}.pem')
    ca_path = os.path.join(cert_dir, 'ca.pem')
    rec = _lane_record(settings, lane_id)
    upk, created = _ensure_user(base, headers, username)
    need_enroll = rec is None or not os.path.isfile(cert_path) or not os.path.isfile(ca_path)
    changed = rec is None or rec.get('channel') != channel or rec.get('ak_pk') != upk
    if changed:
        _set_membership(base, headers, upk, gpk)
        plog(f'  lane {lane_id}: {username} -> member of exactly [{channel}]')
    if need_enroll:
        password = secrets.token_urlsafe(24)
        _set_password(base, headers, upk, password)
        plog(f'  lane {lane_id}: enrolling {username} (CSR -> /Marti/api/tls/signClient/v2)')
        _enroll(username, password, cert_path, ca_path, ctx.get('VERSION', 'dev'), plog, settings=settings)
        del password
    settings = ctx['load_settings']()
    lanes = [r for r in (settings.get('simulator_lanes') or []) if str(r.get('id')) != str(lane_id)]
    rec = {'id': str(lane_id), 'user': username, 'ak_pk': upk, 'channel': channel,
           'cert': cert_path, 'enrolled_at': (rec or {}).get('enrolled_at') if not need_enroll else time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}
    lanes.append(rec)
    lanes.sort(key=lambda r: r['id'])
    settings['simulator_lanes'] = lanes
    ctx['save_settings'](settings)
    _write_lanes_json(settings)
    if need_enroll:
        _audit(f'lane {lane_id} ({username}) enrolled on {channel}')
    elif changed:
        _audit(f'lane {lane_id} ({username}) channel -> {channel}')
    return rec


